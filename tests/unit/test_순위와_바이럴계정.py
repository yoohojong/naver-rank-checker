from scripts import collect_comment_brands as C  # noqa: E402


def _m(키워드, 순위, 글, 표시="안티트로", 키="안티트로", 글쓴이="바이럴이",
       글쓴이키="ZZZ", 원천="댓글", 카페="어떤카페"):
    return {"키워드": 키워드, "순위": 순위, "글": 글, "표시": 표시, "키": 키,
            "종류": "",
            "글쓴이": 글쓴이, "글쓴이키": 글쓴이키, "원천": 원천, "카페": 카페,
            "카페번호": "111", "댓글": "안티트로 써요", "우리놓침": False,
            "구좌": "AB", "제목": f"{키워드} 후기"}


_판정 = {"안티트로": {"제품": True, "이름": "안티트로"},
        "맥단비": {"제품": True, "이름": "맥단비"}}


# ── 경쟁사 순위 ──────────────────────────────────────────────

def test_경쟁사에_최고순위와_평균순위가_붙는다():
    ms = [_m("지루성두피염샴푸", 2, "u1"), _m("비듬샴푸", 4, "u2")]
    r = C.confirmed_rows(ms, _판정)[0]
    assert r["최고순위"] == 2
    assert r["평균순위"] == 3.0


def test_같은_키워드에_여러_글이면_가장_좋은_순위를_쓴다():
    """한 키워드에서 그 브랜드가 2위·5위 두 자리에 있으면 그 키워드 성적은 2위다."""
    ms = [_m("지루성두피염샴푸", 5, "u1"), _m("지루성두피염샴푸", 2, "u2")]
    r = C.confirmed_rows(ms, _판정)[0]
    assert r["순위별"] == {"지루성두피염샴푸": 2}
    assert r["최고순위"] == 2


def test_순위가_없는_언급은_평균을_흐리지_않는다():
    """순위를 못 받은 글(0)을 1위처럼 세면 성적이 거짓으로 좋아진다."""
    ms = [_m("지루성두피염샴푸", 3, "u1"), _m("비듬샴푸", 0, "u2")]
    r = C.confirmed_rows(ms, _판정)[0]
    assert r["최고순위"] == 3
    assert r["평균순위"] == 3.0
    assert "비듬샴푸" not in r["순위별"]


def test_순위를_하나도_모르면_빈_값이지_0이_아니다():
    """0 위는 없는 순위다. '모른다' 와 '1등보다 좋다' 를 섞으면 표가 거짓말한다."""
    r = C.confirmed_rows([_m("지루성두피염샴푸", 0, "u1")], _판정)[0]
    assert r["최고순위"] == ""
    assert r["평균순위"] == ""


# ── 바이럴 계정 ──────────────────────────────────────────────

def test_계정별로_묶어_키워드수와_순위를_낸다():
    ms = [_m("지루성두피염샴푸", 2, "u1"), _m("비듬샴푸", 4, "u2")]
    rows = C.viral_accounts(ms, _판정)
    assert len(rows) == 1
    a = rows[0]
    assert a["계정"] == "바이럴이" and a["계정키"] == "ZZZ"
    assert a["키워드수"] == 2
    assert a["최고순위"] == 2 and a["평균순위"] == 3.0
    assert set(a["키워드들"]) == {"지루성두피염샴푸", "비듬샴푸"}


def test_같은_글의_댓글_여러_개를_한_번으로_센다():
    """댓글 한 줄마다 언급이 하나씩 생긴다 — 그걸 그대로 세면 수다스러운 글이 1등이 된다."""
    ms = [_m("지루성두피염샴푸", 2, "u1"), _m("지루성두피염샴푸", 2, "u1")]
    a = C.viral_accounts(ms, _판정)[0]
    assert a["키워드수"] == 1
    assert a["글수"] == 1


def test_계정이_미는_제품이_같이_나온다():
    """그 계정 글의 댓글에서 확정된 경쟁사 — 어느 업체 대행인지가 여기서 보인다."""
    ms = [_m("지루성두피염샴푸", 2, "u1", 표시="안티트로", 키="안티트로"),
          _m("비듬샴푸", 3, "u2", 표시="맥단비", 키="맥단비")]
