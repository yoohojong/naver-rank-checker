# ── 시트 표 ──────────────────────────────────────────────────

def _오늘줄(**kw):
    r = {"제품군": "샴푸", "경쟁사": "안티트로", "횟수": 3, "키워드수": 2,
         "키워드들": ["지루성두피염샴푸", "비듬샴푸"], "글들": ["u1"], "댓글 예시": "좋아요",
         "상위노출": 2, "놓친": 1, "최고순위": 2, "평균순위": 3.0,
         "순위별": {"지루성두피염샴푸": 2, "비듬샴푸": 4}}
    r.update(kw)
    return r


def test_표에_순위_칸이_생긴다():
    t = C.build_table([], [_오늘줄()], "2026-09-04")
    head, row = t[0], t[1]
    for 칸 in ("최고순위", "평균순위", "키워드별 순위", "검색량"):
        assert 칸 in head, f"{칸} 칸이 있어야 한다"
    assert row[head.index("최고순위")] == 2
    assert row[head.index("평균순위")] == 3.0
    assert "지루성두피염샴푸 2위" in row[head.index("키워드별 순위")]


def test_키워드별_순위는_좋은_자리부터_적는다():
    t = C.build_table([], [_오늘줄()], "2026-09-04")
    글 = t[1][t[0].index("키워드별 순위")]
    assert 글.index("지루성두피염샴푸") < 글.index("비듬샴푸")


def test_검색량은_덮지_않고_지킨다():
    """검색량은 집 PC 도구가 채우는 칸이다. 매일 도는 이 배치가 덮으면 영영 빈칸이 된다."""
    앞선표 = C.build_table([], [_오늘줄()], "2026-09-03")
    i검 = 앞선표[0].index("검색량")
    앞선표[1][i검] = 8600                      # PC 도구가 채워 넣은 값
    t = C.build_table(앞선표, [_오늘줄()], "2026-09-04")
    assert t[1][t[0].index("검색량")] == 8600


def test_처음_보는_경쟁사의_검색량은_빈칸이다():
    t = C.build_table([], [_오늘줄()], "2026-09-04")
    assert t[1][t[0].index("검색량")] == ""


def test_순위를_모르면_그_칸은_빈칸이다():
    t = C.build_table([], [_오늘줄(최고순위="", 평균순위="", 순위별={})], "2026-09-04")
