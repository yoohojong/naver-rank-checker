def test_바이럴계정_표_모양():
    ms = [_m("지루성두피염샴푸", 2, "u1"), _m("비듬샴푸", 4, "u2")]
    t = C.build_viral_table(C.viral_accounts(ms, _판정))
    head, row = t[0], t[1]
    for 칸 in ("계정", "카페", "우리 키워드 수", "최고순위", "평균순위",
              "뜬 키워드", "키워드별 순위", "미는 제품", "글 수", "글 링크", "프로필"):
        assert 칸 in head, f"{칸} 칸이 있어야 한다"
    assert row[head.index("우리 키워드 수")] == 2
    assert row[head.index("최고순위")] == 2


