"""로그인 없는 키워드 후보 — 남의 글 **제목**에서 LLM 이 뽑은 검색 키워드 중
우리한테 없는 것만 뽑는다.

사장님 프로세스(정본 cafe-external/경쟁사_키워드_역추적_프로세스.md) 갈래 B 의
로그인 없는 축소판. 경쟁사 배치가 이미 훑은 제목을 다른 축으로 세기만 한다(추가 크롤 0).

★2026-09-06 재설계: 전에는 브랜드 추출기(candidates_from_title)를 그대로 써서
제목에서 브랜드 조각을 뽑았다 — 게시판 이름·조사·문장 조각이 그대로 후보가 돼
잡음이 심했다(실물 416줄 대부분 쓰레기). 이제 제목→검색 키워드 판정(LLM)을
붙이고, 그 결과를 이 순수함수에 **인자로 주입**한다. 그래서 가짜 LLM 결과로 검사한다.

세는 부분은 순수함수라 파일·시트·네트워크·LLM 을 모른다 — 가짜 판정으로 검사한다.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from scripts import collect_comment_brands as C  # noqa: E402


def _정규(s):
    return C._키워드정규화(s)


def _가짜뽑기(제목별키워드: dict):
    """가짜 LLM: 제목 → 키워드 목록을 미리 정해 둔 표로 돌려준다."""
    def 뽑기(제목들):
        return {제목: list(제목별키워드.get(제목, [])) for 제목 in 제목들}
    return 뽑기


def _by_product():
    """경쟁사 배치가 남긴 언급 모양(제품군별) — 제목이 든다."""
    return {
        "샴푸": [
            {"제목": "지루성 두피염 약국 가서 겨우 해결했네요 ㅠㅠ",
             "카페": "탈모카페", "키워드": "비듬샴푸"},
            {"제목": "비듬 때문에 미치겠어요", "카페": "탈모카페", "키워드": "비듬샴푸"},
        ],
        "바디워시": [
            {"제목": "등 여드름 올라와서 미스트 뿌리는 중", "카페": "맘카페",
             "키워드": "등여드름"},
        ],
    }


def _표준뽑기():
    """위 _by_product 의 제목들에 대한 좋은 LLM 판정."""
    return _가짜뽑기({
        "지루성 두피염 약국 가서 겨우 해결했네요 ㅠㅠ": ["지루성 두피염"],
        "비듬 때문에 미치겠어요": ["비듬"],
        "등 여드름 올라와서 미스트 뿌리는 중": ["등 여드름"],
    })


def test_제목에서_키워드를_뽑아_제품군별로_담는다():
    줄들 = C.제목_키워드후보(_by_product(), 이미가진=set(), 이미후보=set(),
                        오늘="2026-09-06", 키워드뽑기=_표준뽑기())
    보임 = {줄["키워드"]: 줄["제품군"] for 줄 in 줄들}
    assert 보임.get("지루성 두피염") == "샴푸"
    assert 보임.get("등 여드름") == "바디워시"


def test_우리한테_있는_키워드는_뺀다():
    이미가진 = {_정규("지루성 두피염")}
    줄들 = C.제목_키워드후보(_by_product(), 이미가진=이미가진, 이미후보=set(),
                        오늘="2026-09-06", 키워드뽑기=_표준뽑기())
    assert "지루성 두피염" not in {줄["키워드"] for 줄 in 줄들}


def test_이미_후보에_있는_것도_뺀다():
    이미후보 = {_정규("등 여드름")}
    줄들 = C.제목_키워드후보(_by_product(), 이미가진=set(), 이미후보=이미후보,
                        오늘="2026-09-06", 키워드뽑기=_표준뽑기())
    assert "등 여드름" not in {줄["키워드"] for 줄 in 줄들}


def test_같은_키워드는_한_줄만():
    두번 = {"샴푸": [
        {"제목": "지루성 두피염 어떻게 나았나요", "카페": "가", "키워드": "비듬샴푸"},
        {"제목": "지루성 두피염 재발했어요", "카페": "나", "키워드": "탈모샴푸"},
    ]}
    뽑기 = _가짜뽑기({
        "지루성 두피염 어떻게 나았나요": ["지루성 두피염"],
        "지루성 두피염 재발했어요": ["지루성 두피염"],
    })
    줄들 = C.제목_키워드후보(두번, 이미가진=set(), 이미후보=set(),
                        오늘="2026-09-06", 키워드뽑기=뽑기)
    assert [줄["키워드"] for 줄 in 줄들].count("지루성 두피염") == 1


def test_잡음_제목은_후보로_안_나온다():
    """게시판 이름·조사·문장 조각·브랜드뿐인 제목은 LLM 이 빈 목록을 주고,
    그러면 후보로 한 줄도 안 나온다. 진짜 검색 키워드만 남는다.
    """
    자료 = {"샴푸": [
        {"제목": "육아,커뮤니티", "카페": "맘카페", "키워드": "비듬샴푸"},
        {"제목": "머릿결이 뻣뻣한", "카페": "탈모카페", "키워드": "비듬샴푸"},
        {"제목": "다들 계세요?", "카페": "탈모카페", "키워드": "비듬샴푸"},
        {"제목": "안티트로 샴푸 진짜 좋아요", "카페": "탈모카페", "키워드": "비듬샴푸"},
        {"제목": "지루성 두피염 약국 가서 겨우 해결했네요 ㅠㅠ",
         "카페": "탈모카페", "키워드": "비듬샴푸"},
    ]}
    뽑기 = _가짜뽑기({
        "육아,커뮤니티": [],                       # 게시판 이름
        "머릿결이 뻣뻣한": [],                      # 문장 조각
        "다들 계세요?": [],                        # 조사·인사
        "안티트로 샴푸 진짜 좋아요": [],            # 브랜드뿐(경쟁사에서 다룸)
        "지루성 두피염 약국 가서 겨우 해결했네요 ㅠㅠ": ["지루성 두피염"],
    })
    줄들 = C.제목_키워드후보(자료, 이미가진=set(), 이미후보=set(),
                        오늘="2026-09-06", 키워드뽑기=뽑기)
    키워드들 = [줄["키워드"] for 줄 in 줄들]
    assert 키워드들 == ["지루성 두피염"]
    for 잡음 in ("육아,커뮤니티", "머릿결이 뻣뻣한", "다들 계세요?",
               "안티트로 샴푸 진짜 좋아요", "안티트로 샴푸"):
        assert 잡음 not in 키워드들


def test_LLM_이_아무것도_안_뽑으면_빈_목록():
    """열쇠(LLM)가 없어 빈 결과가 오면 후보를 지어내지 않는다."""
    빈뽑기 = _가짜뽑기({})   # 어떤 제목도 키워드가 없음
    줄들 = C.제목_키워드후보(_by_product(), 이미가진=set(), 이미후보=set(),
                        오늘="2026-09-06", 키워드뽑기=빈뽑기)
    assert 줄들 == []


def test_머리줄과_문구가_정본과_같다():
    assert C.키워드후보_머리줄 == ["키워드", "제품군", "접촉지점", "MB", "PC", "총합",
                             "발견경로", "대상카페", "제안자", "제안일",
                             "중복체크(자동)", "주제 분류"]
    줄들 = C.제목_키워드후보(_by_product(), 이미가진=set(), 이미후보=set(),
                        오늘="2026-09-06", 키워드뽑기=_표준뽑기())
    한줄 = 줄들[0]
    assert 한줄["발견경로"] == "남의 글 제목"
    assert 한줄["제안자"] == "자동(제목)"
    assert 한줄["제안일"] == "2026-09-06"
    # 검색량은 비워 둔다 — 집 PC 검색량 도구가 나중에 채운다.
    assert 한줄["MB"] == "" and 한줄["PC"] == "" and 한줄["총합"] == ""


def test_표로_바꾸면_머리줄_순서를_따른다():
    줄들 = C.제목_키워드후보(_by_product(), 이미가진=set(), 이미후보=set(),
                        오늘="2026-09-06", 키워드뽑기=_표준뽑기())
    표 = C.키워드후보_표로(줄들)
    assert len(표) == len(줄들)
    assert len(표[0]) == len(C.키워드후보_머리줄)
    # 발견경로 칸 위치가 머리줄과 맞물린다
    i = C.키워드후보_머리줄.index("발견경로")
    assert 표[0][i] == "남의 글 제목"


def test_제목이_없으면_아무것도_안_뽑는다():
    빈 = {"샴푸": [{"제목": "", "카페": "가", "키워드": "비듬샴푸"}]}
    # 제목이 없으면 LLM 을 부를 것도 없다 — 뽑기를 줘도 빈 결과.
    assert C.제목_키워드후보(빈, 이미가진=set(), 이미후보=set(),
                        키워드뽑기=_가짜뽑기({})) == []
