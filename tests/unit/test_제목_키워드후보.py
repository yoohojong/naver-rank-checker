# -*- coding: utf-8 -*-
"""로그인 없는 키워드 후보 — 남의 글 **제목**에서 우리한테 없는 것만 뽑는다.

사장님 프로세스(정본 cafe-external/경쟁사_키워드_역추적_프로세스.md) 갈래 B 의
로그인 없는 축소판. 경쟁사 배치가 이미 훑은 제목을 다른 축으로 세기만 한다(추가 크롤 0).

세는 부분은 순수함수라 파일·시트·네트워크를 모른다 — 가짜 자료로 검사한다.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from scripts import collect_comment_brands as C  # noqa: E402


def _정규(s):
    return C._키워드정규화(s)


def _by_product():
    """경쟁사 배치가 남긴 언급 모양(제품군별) — 제목이 든다."""
    return {
        "샴푸": [
            {"제목": "안티트로 샴푸 진짜 좋아요", "카페": "탈모카페", "키워드": "비듬샴푸"},
            {"제목": "비듬샴푸 뭐 쓰세요?", "카페": "탈모카페", "키워드": "비듬샴푸"},
        ],
        "두드러기": [
            {"제목": "더마렉신 크림 후기", "카페": "맘카페", "키워드": "두드러기크림"},
        ],
    }


def test_제목에서_후보를_뽑아_제품군별로_담는다():
    줄들 = C.제목_키워드후보(_by_product(), 이미가진=set(), 이미후보=set(),
                        오늘="2026-09-05")
    보임 = {줄["키워드"]: 줄["제품군"] for 줄 in 줄들}
    assert "안티트로 샴푸" in 보임 and 보임["안티트로 샴푸"] == "샴푸"
    assert "더마렉신 크림" in 보임 and 보임["더마렉신 크림"] == "두드러기"


def test_우리한테_있는_키워드는_뺀다():
    이미가진 = {_정규("안티트로 샴푸")}
    줄들 = C.제목_키워드후보(_by_product(), 이미가진=이미가진, 이미후보=set(),
                        오늘="2026-09-05")
    assert "안티트로 샴푸" not in {줄["키워드"] for 줄 in 줄들}


def test_이미_후보에_있는_것도_뺀다():
    이미후보 = {_정규("더마렉신 크림")}
    줄들 = C.제목_키워드후보(_by_product(), 이미가진=set(), 이미후보=이미후보,
                        오늘="2026-09-05")
    assert "더마렉신 크림" not in {줄["키워드"] for 줄 in 줄들}


def test_같은_후보는_한_줄만():
    두번 = {"샴푸": [
        {"제목": "안티트로 샴푸 좋아요", "카페": "가", "키워드": "비듬샴푸"},
        {"제목": "안티트로 샴푸 재구매", "카페": "나", "키워드": "탈모샴푸"},
    ]}
    줄들 = C.제목_키워드후보(두번, 이미가진=set(), 이미후보=set(), 오늘="2026-09-05")
    assert [줄["키워드"] for 줄 in 줄들].count("안티트로 샴푸") == 1


def test_머리줄과_문구가_정본과_같다():
    assert C.키워드후보_머리줄 == ["키워드", "제품군", "접촉지점", "MB", "PC", "총합",
                             "발견경로", "대상카페", "제안자", "제안일",
                             "중복체크(자동)", "주제 분류"]
    줄들 = C.제목_키워드후보(_by_product(), 이미가진=set(), 이미후보=set(),
                        오늘="2026-09-05")
    한줄 = 줄들[0]
    assert 한줄["발견경로"] == "남의 글 제목"
    assert 한줄["제안자"] == "자동(제목)"
    assert 한줄["제안일"] == "2026-09-05"
    # 검색량은 비워 둔다 — 집 PC 검색량 도구가 나중에 채운다.
    assert 한줄["MB"] == "" and 한줄["PC"] == "" and 한줄["총합"] == ""


def test_표로_바꾸면_머리줄_순서를_따른다():
    줄들 = C.제목_키워드후보(_by_product(), 이미가진=set(), 이미후보=set(),
                        오늘="2026-09-05")
    표 = C.키워드후보_표로(줄들)
    assert len(표) == len(줄들)
    assert len(표[0]) == len(C.키워드후보_머리줄)
    # 발견경로 칸 위치가 머리줄과 맞물린다
    i = C.키워드후보_머리줄.index("발견경로")
    assert 표[0][i] == "남의 글 제목"


def test_제목이_없으면_아무것도_안_뽑는다():
    빈 = {"샴푸": [{"제목": "", "카페": "가", "키워드": "비듬샴푸"}]}
    assert C.제목_키워드후보(빈, 이미가진=set(), 이미후보=set()) == []
