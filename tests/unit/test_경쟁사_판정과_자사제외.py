def _줄(경쟁사="안티트로", 제품군="샴푸", 횟수=3, 키워드수=2):
    return {"제품군": 제품군, "경쟁사": 경쟁사, "횟수": 횟수, "키워드수": 키워드수,
            "키워드들": ["가", "나"], "글들": ["u1"], "댓글 예시": "",
            "놓친": 0, "최고순위": 1, "평균순위": 1.0, "키워드별순위": "가 AB 1위"}


def _검색량_넣은_지난표(값들: dict, 오늘="2026-09-04"):
    """지난 표를 만들고 검색량 칸에 값을 손으로 적어 넣는다(집 PC 도구가 하는 일)."""
    표 = C.build_table([], [_줄(경쟁사=n) for n in 값들], 오늘)
    머리 = 표[0]
    ib, iv = 머리.index("경쟁사"), 머리.index("검색량")
    for 줄 in 표[1:]:
        줄[iv] = 값들[줄[ib]]
    return 표


def test_판정칸은_검색량_바로_뒤에_있다():
    머리 = C.build_table([], [_줄()], "2026-09-05")[0]
    assert "판정" in 머리
    assert 머리.index("판정") == 머리.index("검색량") + 1, 머리


