def test_이어받는_옛_줄에도_자사_가게_성분을_거른다():
    """★2026-09-05 실물 확인: 제외가 생기기 전에 시트에 들어온 두드럼(자사)·다이소(가게)·
    케라틴(성분)이 build_table 이어받기로 눌러앉아 있었다. 오늘 out_rows 에 없어도
    이어받을 때 같은 잣대로 걸러야 한다."""
    머리 = C.FIXED_HEAD + ["2026-09-05", "2026-09-04"]
    def 옛줄(제품군, 이름):
        r = [""] * len(머리)
        r[머리.index("제품군")] = 제품군
        r[머리.index("경쟁사")] = 이름
        r[머리.index("2026-09-04")] = "6"      # 지난 날 값이 있어 7일 창에서 안 내려감
        r[머리.index("뜬 키워드 수")] = "6"
        return r
    prev = [머리, 옛줄("두드러기", "두드럼"), 옛줄("두드러기", "케라틴"),
            옛줄("바디워시", "다이소"), 옛줄("두드러기", "아토엠")]
    표 = C.build_table(prev, [], "2026-09-05")
    이름들 = {r[표[0].index("경쟁사")] for r in 표[1:]}
    assert "아토엠" in 이름들, "진짜 경쟁사는 이어받아야 한다"
    assert not ({"두드럼", "케라틴", "다이소"} & 이름들), 이름들
