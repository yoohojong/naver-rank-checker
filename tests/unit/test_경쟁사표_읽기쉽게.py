# -*- coding: utf-8 -*-
"""경쟁사 표를 사장님이 읽을 수 있게 — 2026-09-04 사장님 지적.

사장님 원문: "경쟁사 탭도 지금 다시 만들어줘야지 무슨 행 길이가 이렇게 길어?
그리고 제대로 된 나온 키워드도 아니야. 그리고 날짜를 왜 저렇게 해둬?"

실제 시트를 열어 보니(그 전까지 **한 번도 안 봤다**):
  · 날짜 칸이 2026-07-24~07-18 — 6주 전에 굳어 있었다
  · 댓글 예시가 한 칸에 통째로 들어가 **행 높이**를 키웠다
  · 글 링크가 여러 개라 줄바꿈으로 또 키웠다
  · 날짜 7칸이 표 한가운데 있어 정작 볼 숫자를 오른쪽 밖으로 밀어냈다

고침: 읽는 순서대로 칸을 놓고, 행을 키우는 두 칸을 없애고, 날짜는 3칸만 맨 뒤로.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from scripts import collect_comment_brands as C  # noqa: E402


def _줄(**kw):
    r = {"제품군": "샴푸", "경쟁사": "안티트로", "횟수": 3, "키워드수": 2,
         "키워드들": ["가", "나"], "글들": ["u1", "u2", "u3"], "댓글 예시": "좋아요",
         "놓친": 1, "최고순위": 2, "평균순위": 3.0,
         "순위별": [{"키워드": "가", "구좌": "AB", "순위": 2}],
         "키워드별순위": "가 AB 2위"}
    r.update(kw)
    return r


def test_읽는_순서대로_놓는다():
    """이름·성적이 먼저, 날짜는 맨 뒤. 볼 숫자가 오른쪽 밖으로 밀리면 안 된다."""
    머리 = C.build_table([], [_줄()], "2026-09-04")[0]
    앞 = 머리[:7]
    assert 앞[:2] == ["제품군", "경쟁사"]
    for 칸 in ("검색량", "뜬 키워드 수", "최고순위", "평균순위"):
        assert 칸 in 앞, f"{칸} 이 앞쪽에 있어야 한다 — 지금 머리줄: {머리}"
    import re
    첫날짜 = next(i for i, c in enumerate(머리) if re.fullmatch(r"\d{4}-\d{2}-\d{2}", c))
    assert 첫날짜 >= len(머리) - 3, "날짜는 맨 뒤 3칸이어야 한다"


def test_행을_키우던_두_칸을_없앴다():
    """댓글 예시(통째로 들어감)와 여러 줄 글 링크가 행 높이의 주범이었다."""
    머리 = C.build_table([], [_줄()], "2026-09-04")[0]
    assert "댓글 예시" not in 머리
    assert "나온 키워드" not in 머리, "'어느 키워드 몇 위' 가 그 자리를 대신한다"


def test_글_링크는_하나만():
    t = C.build_table([], [_줄()], "2026-09-04")
    링크 = t[1][t[0].index("글 링크")]
    assert 링크 == "u1", f"여러 개면 줄바꿈으로 행이 커진다: {링크!r}"


def test_날짜는_사흘치만():
    머리 = C.build_table([], [_줄()], "2026-09-04")[0]
    import re
    날짜 = [c for c in 머리 if re.fullmatch(r"\d{4}-\d{2}-\d{2}", c)]
    assert len(날짜) == 3, f"일곱 칸은 표를 넓게만 만든다: {날짜}"
    assert 날짜[0] == "2026-09-04"


def test_칸_이름이_무엇인지_바로_알린다():
    """말 규칙 제1조 — 읽는 순간 뜻이 잡혀야 한다."""
    머리 = C.build_table([], [_줄()], "2026-09-04")[0]
    assert "7일 댓글 수" in 머리, "'최근7일 합계' 는 무엇의 합계인지 안 보인다"
    assert "어느 키워드 몇 위" in 머리


def test_지난_표에서_날짜를_그대로_이어_읽는다():
    """칸 자리를 옮겨도 어제까지의 기록은 살아 있어야 한다."""
    어제 = C.build_table([], [_줄(횟수=5)], "2026-09-03")
    오늘 = C.build_table(어제, [_줄(횟수=2)], "2026-09-04")
    머리, 줄 = 오늘[0], 오늘[1]
    assert 줄[머리.index("2026-09-04")] == 2
    assert 줄[머리.index("2026-09-03")] == 5
