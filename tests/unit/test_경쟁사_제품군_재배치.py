def test_옮겨간_줄은_오늘_센_값을_지킨다():
    """★훑은 탭에서 주웠는데 안 훑은 제품군으로 옮겨 앉으면 오늘 값이 버려졌다.

    훑은 탭 목록은 **옮기기 전** 이름들이다. 안티트로를 오늘 바디워시 탭에서
    주웠지만 파는 것이 샴푸라 샴푸 줄로 간다 — 그런데 오늘 샴푸 탭은 못 훑었다.
    그러면 '뜬 키워드 수' 에는 오늘 값이 적히는데 옆의 오늘 칸은 '오늘은 못 봄'
    이라, 한 줄 안에서 두 칸이 서로 다른 말을 한다.
    """
    지난 = _지난표([
        {"제품군": "샴푸", "경쟁사": "안티트로", "검색량": "12580",
         "파는 제품군": "샴푸", "2026-09-08": "1"},
        {"제품군": "샴푸", "경쟁사": "옆줄브랜드", "뜬 키워드 수": "4",
         "2026-09-08": "6"},
    ])
    오늘 = [_오늘줄(경쟁사="안티트로", 제품군="샴푸", 횟수=3)]
    표 = C.build_table(지난, 오늘, "2026-09-09",
                      scanned_products={"바디워시", "두드러기"})
    머리 = 표[0]
    줄 = next(r for r in 표[1:] if r[머리.index("경쟁사")] == "안티트로")
    assert 줄[머리.index("2026-09-09")] == 3, "오늘 센 값을 버리면 안 된다"
    assert 줄[머리.index("추세")] != "오늘은 못 봄"
    assert 줄[머리.index("뜬 키워드 수")] == 2

    # 오늘 안 나온 옆 줄은 그대로 '못 봄' 이다 — 한 줄이 통을 열어 주면 안 된다.
    옆 = next(r for r in 표[1:] if r[머리.index("경쟁사")] == "옆줄브랜드")
    assert 옆[머리.index("2026-09-09")] == ""
    assert 옆[머리.index("추세")] == "오늘은 못 봄"


