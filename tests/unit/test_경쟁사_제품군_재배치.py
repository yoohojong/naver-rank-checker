def test_숫자칸_서식이_제자리에_간다():
    """★칸이 늘면 자리로 적어 둔 서식이 엉뚱한 데 간다 — 이름으로 고르는지 본다."""
    머리 = C.build_table([], [_오늘줄()], "2026-09-09")[0]
    가운데, 줄바꿈 = C.서식_칸묶음(머리)
    def 덮인칸(묶음들):
        return {머리[i] for a, b in 묶음들 for i in range(a, b)}
    숫자 = 덮인칸(가운데)
    for 칸 in ("검색량", "뜬 키워드 수", "최고순위", "평균순위", "7일 댓글 수",
              "우리가 놓친", "2026-09-09"):
        assert 칸 in 숫자, f"{칸} 은 숫자칸인데 가운데 정렬에서 빠졌다"
    글 = 덮인칸(줄바꿈)
    for 칸 in ("검색량 키워드", "파는 제품군", "판정", "어느 키워드 몇 위", "글 링크"):
        assert 칸 in 글, f"{칸} 은 글인데 줄바꿈에서 빠졌다"
    assert not (숫자 & 글), "한 칸이 두 서식에 걸리면 안 된다"
    assert "제품군" not in 글 and "경쟁사" not in 글, "얼어 있는 이름 두 칸은 그대로 둔다"
