# ── ② '파는 제품군' 칸 읽기 ───────────────────────────────────────────────

def _지난표(줄들, 오늘="2026-09-08"):
    """머리줄 + 손으로 적은 옛 줄. 칸 이름으로 찾아 넣는다(자리는 언제든 바뀐다)."""
    머리 = C.FIXED_HEAD + [오늘]
    표 = [머리]
    for 값 in 줄들:
        r = [""] * len(머리)
        for 이름, v in 값.items():
            r[머리.index(이름)] = v
        표.append(r)
    return 표


def test_파는_제품군_칸을_세_가지로_읽는다():
    표 = _지난표([
        {"제품군": "샴푸", "경쟁사": "안물어봄", "검색량": "990", "파는 제품군": ""},
        {"제품군": "샴푸", "경쟁사": "못정함", "검색량": "0",
         "파는 제품군": C.파는제품군_못정함},
        {"제품군": "샴푸", "경쟁사": "두벌", "검색량": "12580",
         "파는 제품군": "샴푸·바디워시"},
    ])
    본 = C._prev_families(표)
    assert "안물어봄" not in 본, "빈 칸은 '모른다' — 열쇠를 만들면 안 된다"
    assert 본["못정함"] == []
    assert 본["두벌"] == ["샴푸", "바디워시"]


