"""보고서에 찍는 제품 이름 — 시트 탭 이름을 사장님이 부르는 이름으로.

사장님 2026-08-05: "성과대시보드나 다른 모든것에서 머드름 샴푸랑 바디워시라고
되어있는거 명칭을 뽀얀샴푸 뽀얀바디워시로 변경해줘"

★시트 탭 이름('샴푸 카외'·'바디워시 카외')은 **안 바꾼다.** 이 프로그램이 그 이름으로
  시트를 찾고, 상위노출 이력도 그 이름으로 쌓여 있다. 찍을 때만 바꾼다.
"""
from __future__ import annotations

_LABEL = {"샴푸": "뽀얀샴푸", "바디워시": "뽀얀바디워시"}


def tab_label(tab: str) -> str:
    """'샴푸 카외' → '뽀얀샴푸'. 규칙에 없는 탭은 ' 카외'만 떼고 그대로."""
    base = str(tab or "").replace(" 카외", "").strip()
    return _LABEL.get(base, base)
